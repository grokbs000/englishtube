def build_cues(raw_list):
    return [
        {"start": start, "duration": dur, "en": en, "zh": zh}
        for start, dur, en, zh in raw_list
    ]

def main():
    with open("songs_50.json", encoding="utf-8") as f:
        songs = json.load(f)

    updated = 0
    for song in songs:
        sid = song["id"]
        if sid in FULL_LYRICS:
            song["cues"] = build_cues(FULL_LYRICS[sid])
            updated += 1
            print(f"✅ Updated: {song['title']} ({len(song['cues'])} cues)")
        else:
            # Extend existing cues to fill gap if possible
            existing = song.get("cues", [])
            if existing:
                # Parse duration
                dur_str = song.get("duration", "4:00")
                parts = dur_str.split(":")
                total_sec = int(parts[0]) * 60 + int(parts[1]) if len(parts) == 2 else 240

                last = existing[-1]
                last_end = last["start"] + last.get("duration", 4)
                remaining = total_sec - last_end

                if remaining > 10:
                    # Add a "reprise" cue that covers the remaining instrumental section
                    existing.append({
                        "start": last_end + 2,
                        "duration": max(5, remaining - 5),
                        "en": f"♪ {existing[0]['en']}",
                        "zh": f"♪ {existing[0]['zh']}"
                    })
                    song["cues"] = existing
                    print(f"⬆️  Extended: {song['title']} (added reprise cue, now {len(existing)} cues)")
                else:
                    print(f"⚠️  Skipped (short gap): {song['title']}")

    with open("songs_50.json", "w", encoding="utf-8") as f:
        json.dump(songs, f, ensure_ascii=False, indent=2)

    print(f"\n✅ Done! Updated {updated} songs with full lyrics.")

if __name__ == "__main__":
    main()
